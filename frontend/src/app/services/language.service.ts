@Injectable({ providedIn: 'root' })
export class LanguageService {
  private readonly document = inject(DOCUMENT);
  readonly language = signal<Language>(this.readLanguage());

  constructor() {
    this.applyDocumentLanguage(this.language());
  }

  setLanguage(language: Language) {
    this.language.set(language);
    if (typeof localStorage !== 'undefined') localStorage.setItem('qpon-language', language);
    this.applyDocumentLanguage(language);
  }

  translate(key: string, fallback = key): string {
    return translations[this.language()][key] ?? translations.en[key] ?? fallback;
  }

  private readLanguage(): Language {
    if (typeof localStorage !== 'undefined') {
      const stored = localStorage.getItem('qpon-language');
      if (stored === 'fr' || stored === 'en') return stored;
    }
    return 'en';
  }

  private applyDocumentLanguage(language: Language) {
    this.document.documentElement.lang = language;
  }
}
